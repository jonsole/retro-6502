#!/usr/bin/env python3
"""Make the ca65 register include (firmware/include/hw.inc) from hw.h.

hw.h is retro-z80's generated C header (its tools/regmap.py, from its
fpga/regmap.def), copied here unchanged (fpga/rtl/PROVENANCE.md). Its
numbers are the same on retro-6502: a system register's name is its register
number, so on the 65C02 it is at SYSREGS + name ($FE00 + n, spec 1, section
6.1); a custom register's name is its custom offset, at the register page's
custom block. Port numbers (the _P names) and the C macros are Z80-only and
are left out.

  python3 tools/hw2ca65.py [hw.h] [hw.inc]
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
src = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "firmware/include/hw.h"
dst = Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / "firmware/include/hw.inc"

out = ["; Generated by tools/hw2ca65.py from hw.h (retro-z80's register names).",
       "; Do not edit. System registers: SYSREGS + name. Custom registers:",
       "; the register page's custom block (REGS_CUSTOM) + name.", "",
       "SYSREGS = $FE00                 ; the system block (spec 1, section 6.1)",
       "REGSPAGE = $3F8                 ; MMU page of the register page", ""]
define = re.compile(r"#define\s+([A-Z][A-Z0-9_]*)\s+(0x[0-9A-Fa-f]+)(?:u|UL)?\b(.*)")
seen = set()
for line in src.read_text().splitlines():
    if line.startswith("/* ----"):
        out.append("; " + line[3:].rstrip(" */"))
        continue
    m = define.match(line)
    if not m:
        continue
    name, val = m.group(1), int(m.group(2), 16)
    if name.endswith("_P") or name in seen or name.startswith("RETROZ80"):
        continue
    if name.endswith("_PORT") or name in ("CUSTPAGE", "IPPAGE", "DBGPAGE"):
        continue
    seen.add(name)
    out.append(f"{name} = ${val:X}")
dst.write_text("\n".join(out) + "\n")
print(f"hw2ca65: {len(seen)} names -> {dst}")
